// Contract tooling (README §11.5):
//   node scripts/contracts.mjs generate   → rewrite openapi.json + src/generated/schema.d.ts from the API code
//   node scripts/contracts.mjs check      → fail if either differs from what the code produces, or if the
//                                           typed client does not compile
// Options (used by tests):  --skip-build  --spec <file>  --types <file>  --tsconfig <file>
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const packageDir = path.resolve(import.meta.dirname, '..');
const repoRoot = path.resolve(packageDir, '../..');
const exporter = path.join(repoRoot, 'apps/api/dist/openapi-export.js');
const require = createRequire(import.meta.url);

const COMMITTED_SPEC = path.join(packageDir, 'openapi.json');
const COMMITTED_TYPES = path.join(packageDir, 'src/generated/schema.d.ts');
const HEADER =
  '/**\n * Generated by openapi-typescript from openapi.json — do not edit.\n * Regenerate with `pnpm contracts:generate`.\n */\n\n';

const args = process.argv.slice(2);
const command = args[0];
const flag = (name) => {
  const index = args.indexOf(name);
  return index === -1 ? undefined : args[index + 1];
};
const skipBuild = args.includes('--skip-build');

const rel = (file) => path.relative(repoRoot, file).split(path.sep).join('/');
const normalize = (text) => text.replaceAll('\r\n', '\n');

function run(file, fileArgs, options = {}) {
  return spawnSync(file, fileArgs, { encoding: 'utf8', cwd: repoRoot, ...options });
}

function buildApi() {
  if (skipBuild) return;
  // pnpm is a .cmd shim on Windows; arguments are static so a shell is safe here.
  const result = run('pnpm --filter @rento/api build', [], { shell: true, stdio: 'inherit' });
  if (result.status !== 0) fail('building the API failed');
}

function exportSpec(outFile) {
  const result = run(process.execPath, [exporter, outFile]);
  if (result.status !== 0) {
    fail(`exporting the OpenAPI document failed:\n${result.stderr || result.stdout}`);
  }
}

async function typesFrom(specFile) {
  const ast = await openapiTS(pathToFileURL(specFile));
  return HEADER + astToString(ast);
}

function fail(message) {
  console.error(`contracts: FAILED — ${message}`);
  process.exit(1);
}

function firstDifference(a, b) {
  const left = normalize(a).split('\n');
  const right = normalize(b).split('\n');
  const length = Math.max(left.length, right.length);
  for (let i = 0; i < length; i += 1) {
    if (left[i] !== right[i]) return `first difference at line ${i + 1}`;
  }
  return 'contents differ';
}

function compare(label, committedFile, fresh) {
  let committed;
  try {
    committed = readFileSync(committedFile, 'utf8');
  } catch {
    fail(`${rel(committedFile)} is missing. Run: pnpm contracts:generate`);
  }
  if (normalize(committed) !== normalize(fresh)) {
    fail(
      `${label} drift: ${rel(committedFile)} does not match what the API produces ` +
        `(${firstDifference(committed, fresh)}). Run: pnpm contracts:generate`,
    );
  }
  console.log(`ok  ${rel(committedFile)} is up to date`);
}

async function generate() {
  buildApi();
  const tmp = mkdtempSync(path.join(os.tmpdir(), 'rento-contracts-'));
  try {
    const spec = path.join(tmp, 'openapi.json');
    exportSpec(spec);
    const types = await typesFrom(spec);
    writeFileSync(COMMITTED_SPEC, readFileSync(spec, 'utf8'), 'utf8');
    mkdirSync(path.dirname(COMMITTED_TYPES), { recursive: true });
    writeFileSync(COMMITTED_TYPES, types, 'utf8');
    console.log(`wrote ${rel(COMMITTED_SPEC)} and ${rel(COMMITTED_TYPES)}`);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

async function check() {
  buildApi();
  const tmp = mkdtempSync(path.join(os.tmpdir(), 'rento-contracts-'));
  try {
    const freshSpecFile = path.join(tmp, 'openapi.json');
    exportSpec(freshSpecFile);
    const freshSpec = readFileSync(freshSpecFile, 'utf8');

    let freshTypes;
    try {
      freshTypes = await typesFrom(freshSpecFile); // also proves the document is valid OpenAPI 3
    } catch (error) {
      fail(
        `the generated OpenAPI document is not valid: ${error instanceof Error ? error.message : error}`,
      );
    }

    compare('spec', flag('--spec') ?? COMMITTED_SPEC, freshSpec);
    compare('types', flag('--types') ?? COMMITTED_TYPES, freshTypes);

    const tsc = require.resolve('typescript/bin/tsc');
    const tsconfig = flag('--tsconfig') ?? path.join(packageDir, 'tsconfig.json');
    const compiled = run(process.execPath, [tsc, '--noEmit', '-p', tsconfig]);
    if (compiled.status !== 0) {
      fail(`the typed client does not compile:\n${compiled.stdout || compiled.stderr}`);
    }
    console.log('ok  the typed client compiles');
    console.log('contracts:check passed');
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

if (command === 'generate') await generate();
else if (command === 'check') await check();
else
  fail(
    'usage: contracts.mjs <generate|check> [--skip-build] [--spec f] [--types f] [--tsconfig f]',
  );
